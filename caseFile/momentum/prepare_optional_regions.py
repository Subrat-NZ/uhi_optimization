#!/usr/bin/env python3
"""Generate snappyHexMesh include files from the OBJ surfaces in a case.
RUN it as: python3 prepare_optional_regions.py --level 2 --max-level 3
Only OBJ files containing at least one vertex and one face are enabled.  This
is important because json_to_obj.py deliberately writes empty placeholder
files for entity types that are absent from the input JSON.

The generated geometry names are prefixed with ``obj_``.  That keeps a
``ground.obj`` surface distinct from the background-mesh patch named
``ground`` while the common ``wall`` patch group supplies boundary conditions
for both.
"""

from __future__ import annotations

import argparse
import os
import re
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence


# These are visualisation/intermediate surfaces, not CFD obstacles.
IGNORED_NAMES = {
    "site_boundary.obj",
    "site_boundary_shifted.obj",
    "buildingsorig.obj",
    "buildings_original.obj",
}


@dataclass(frozen=True)
class Surface:
    path: Path
    geometry_name: str
    vertices: int
    faces: int

    @property
    def feature_file(self) -> str:
        return f"{self.path.stem}.eMesh"


def obj_counts(path: Path) -> tuple[int, int]:
    """Return the number of position vertices and non-degenerate face lines."""
    vertices = 0
    faces = 0
    with path.open("r", encoding="utf-8", errors="ignore") as stream:
        for raw_line in stream:
            fields = raw_line.lstrip().split()
            if not fields:
                continue
            if fields[0] == "v" and len(fields) >= 4:
                vertices += 1
            elif fields[0] == "f" and len(fields) >= 4:
                faces += 1
    return vertices, faces


def foam_word(value: str) -> str:
    """Convert an OBJ stem into a conservative OpenFOAM dictionary keyword."""
    word = re.sub(r"[^A-Za-z0-9_]", "_", value)
    word = re.sub(r"_+", "_", word).strip("_") or "surface"
    if word[0].isdigit():
        word = f"surface_{word}"
    return f"obj_{word}"


def discover_surfaces(surface_dir: Path) -> tuple[list[Surface], list[str]]:
    warnings: list[str] = []
    candidates: list[tuple[Path, int, int]] = []

    for path in sorted(surface_dir.iterdir(), key=lambda item: item.name.lower()):
        if not path.is_file() or path.suffix.lower() != ".obj":
            continue
        lower_name = path.name.lower()
        if lower_name in IGNORED_NAMES or lower_name.endswith("_edgemesh.obj"):
            warnings.append(f"ignored helper surface: {path.name}")
            continue
        vertices, faces = obj_counts(path)
        if vertices == 0 or faces == 0:
            warnings.append(
                f"ignored empty surface: {path.name} "
                f"({vertices} vertices, {faces} faces)"
            )
            continue
        candidates.append((path, vertices, faces))

    # buildings_refined.obj and buildings.obj normally describe the same
    # buildings. Prefer the refined mesh when both exist to avoid coincident
    # duplicate surfaces in snappyHexMesh.
    names = {path.name.lower() for path, _, _ in candidates}
    if "buildings_refined.obj" in names and "buildings.obj" in names:
        candidates = [
            item for item in candidates if item[0].name.lower() != "buildings.obj"
        ]
        warnings.append(
            "ignored buildings.obj because buildings_refined.obj is present"
        )

    used_names: set[str] = set()
    surfaces: list[Surface] = []
    for path, vertices, faces in candidates:
        geometry_name = foam_word(path.stem)
        base_name = geometry_name
        suffix = 2
        while geometry_name in used_names:
            geometry_name = f"{base_name}_{suffix}"
            suffix += 1
        used_names.add(geometry_name)
        surfaces.append(Surface(path, geometry_name, vertices, faces))

    return surfaces, warnings


def render_geometry(surfaces: Sequence[Surface]) -> str:
    chunks = ["// Generated by prepare_optional_regions.py; do not edit.\n"]
    for surface in surfaces:
        chunks.append(
            f"{surface.geometry_name}\n"
            "{\n"
            "    type triSurfaceMesh;\n"
            f'    file "{surface.path.name}";\n'
            "}\n\n"
        )
    return "".join(chunks)


def render_features(surfaces: Sequence[Surface], level: int) -> str:
    chunks = ["// Generated by prepare_optional_regions.py; do not edit.\n"]
    for surface in surfaces:
        chunks.append(
            f'{{ file "{surface.feature_file}"; level {level}; }}\n'
        )
    return "".join(chunks)


def render_refinement(surfaces: Sequence[Surface], level: int, max_level: int) -> str:
    chunks = ["// Generated by prepare_optional_regions.py; do not edit.\n"]
    for surface in surfaces:
        chunks.append(
            f"{surface.geometry_name}\n"
            "{\n"
            f"    level ({level} {max_level});\n"
            "    patchInfo\n"
            "    {\n"
            "        type wall;\n"
            "        inGroups (wall);\n"
            "    }\n"
            "}\n\n"
        )
    return "".join(chunks)


def render_surface_list(surfaces: Sequence[Surface]) -> str:
    chunks = ["// Generated by prepare_optional_regions.py; do not edit.\n"]
    chunks.extend(f'"{surface.path.name}"\n' for surface in surfaces)
    return "".join(chunks)


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(temporary_name, path)
    except BaseException:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass
        raise


def write_includes(
    system_dir: Path, surfaces: Sequence[Surface], level: int, max_level: int
) -> None:
    outputs: Iterable[tuple[str, str]] = (
        ("optionalGeometry", render_geometry(surfaces)),
        ("optionalFeatures", render_features(surfaces, level)),
        ("optionalRefinementSurfaces", render_refinement(surfaces, level, max_level)),
        ("optionalSurfaceFeatureSurfaces", render_surface_list(surfaces)),
    )
    for name, content in outputs:
        atomic_write(system_dir / name, content)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--surface-dir",
        type=Path,
        default=Path("constant/triSurface"),
        help="directory containing OBJ surfaces (default: constant/triSurface)",
    )
    parser.add_argument(
        "--system-dir",
        type=Path,
        default=Path("system"),
        help="directory in which include files are written (default: system)",
    )
    parser.add_argument(
        "--level",
        type=int,
        default=2,
        help="feature refinement level and minimum surface refinement level (default: 2)",
    )
    parser.add_argument(
        "--max-level",
        type=int,
        default=None,
        help=(
            "maximum surface refinement level, i.e. the second number of "
            "'level (min max)' (default: --level + 1, so 2 -> level (2 3))"
        ),
    )
    parser.add_argument(
        "--allow-empty",
        action="store_true",
        help="write empty include files instead of failing when no usable OBJ exists",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.level < 0:
        raise SystemExit("error: --level must be zero or greater")
    max_level = args.level + 1 if args.max_level is None else args.max_level
    if max_level < args.level:
        raise SystemExit("error: --max-level must not be smaller than --level")
    if not args.surface_dir.is_dir():
        raise SystemExit(f"error: surface directory not found: {args.surface_dir}")

    surfaces, warnings = discover_surfaces(args.surface_dir)
    for warning in warnings:
        print(f"WARNING: {warning}")

    if not surfaces and not args.allow_empty:
        raise SystemExit(
            f"error: no non-empty OBJ surfaces found in {args.surface_dir}"
        )

    write_includes(args.system_dir, surfaces, args.level, max_level)
    if surfaces:
        print(
            f"Refinement: features level {args.level}, "
            f"surfaces level ({args.level} {max_level})"
        )
        print("Enabled OBJ surfaces:")
        for surface in surfaces:
            print(
                f"  {surface.path.name} -> {surface.geometry_name} "
                f"({surface.vertices} vertices, {surface.faces} faces)"
            )
    else:
        print("No OBJ surfaces enabled; empty include files written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())