"""
PRODUCTION INFERENCE — pix2pix UHI Field Predictor
==============================================================

This script is intended exclusively for INFERENCE. The entire pytorch-CycleGAN-and-pix2pix repository is not required in production. The generator architecture is implemented directly in this self-contained file, copied from models/networks.py.

UPDATED INPUT FORMAT:
    Previously, this script used an outdated, separate 12-channel input format
    designed for temperature (T) prediction. This format did not match
    data/uhi_npy_dataset.py.

    The dataset class always includes aux_field2 (the full-raster T field) and
    never creates U_inlet channels, because that file is never generated by the
    dataset. Only the target field's own inlet data is included.

    Both files now generate EXACTLY the same input format, eliminating any
    mismatch between training and inference.

Training command (reference, from which this script was derived):
    python train.py --dataroot ... --model pix2pix --dataset_mode uhi_npy 
        --target_field w --aux_field U --use_inlet 1 
        --input_nc 11 --output_nc 1 --norm_stats_json ... 
        --netG unet_512 --netD n_layers --n_layers_D 1 ...

    Use --use_inlet 0 --input_nc 9 if inlet channels are not required.

IMPORTANT ARCHITECTURE NOTE:
    The --norm option was not explicitly specified in the training command.
    However, Pix2PixModel.modify_commandline_options() sets norm="batch" as the
    DEFAULT when --model pix2pix is selected, overriding the base default of
    "instance".

    Therefore, the actual trained generator uses BatchNorm2d, not InstanceNorm2d.

    If you encounter a "size mismatch" or "missing keys" error while loading
    the model, first check the checkpoints_dir/<name>/opt.txt file, if it was
    saved, to confirm the values of norm: and ngf:. Update the NORM_TYPE / NGF
    constants below accordingly.

Model input order (9 or 11 channels) — matches data/uhi_npy_dataset.py EXACTLY:
    0-5   : Geometry one-hot encoding (6 classes, IDs 1-6 mapped to channels 0-5)
    6     : Auxiliary field (default U), normalized to [-1, 1], full raster
    7     : Auxiliary field 2 (fixed T), normalized to [-1, 1], full raster
    8     : Valid/fluid mask ({-1, 1}) -- solid (building) = -1, fluid = 1

    The following channels are included only when --use_inlet 1 is enabled
    (the default). Otherwise, the input ends at channel 8, giving input_nc=9.

    9     : Target field's own inlet value, normalized to [-1, 1] (0 where not inlet)
    10    : Target field's own inlet mask ({-1, 1}) -- known = 1, unknown = -1

Usage (use_inlet=1, default; target=w, matching the current training configuration):
    python predict_RH.py ^
        --geometry     NASH00040_10800_geometry_labels.npy ^
        --aux_label    NASH00040_10800_U_labels.npy ^
        --aux2_label   NASH00040_10800_T_labels.npy ^
        --target_inlet NASH00040_10800_w_inlet_labels.npy ^
        --checkpoint   "C:\\...\\model\\latest_net_G.pth" ^
        --norm_stats   "C:\\...\\model\\norm_stats.json" ^
        --out_dir      "C:\\...\\predictions" ^
        --case_name    NASH00040 --timestep 10800 --target_field w

Usage (use_inlet=0; checkpoint must be trained with --use_inlet 0 and input_nc=9):
    python predict_T.py ^
        --geometry     NASH00040_10800_geometry_labels.npy ^
        --aux_label    NASH00040_10800_U_labels.npy ^
        --aux2_label   NASH00040_10800_T_labels.npy ^
        --no_inlet ^
        --checkpoint   "C:\\...\\model\\latest_net_G.pth" ^
        --norm_stats   "C:\\...\\model\\norm_stats.json" ^
        --out_dir      "C:\\...\\predictions" ^
        --case_name    NASH00040 --timestep 10800 --target_field w

Output:
    <out_dir>/<case>_<ts>_w_predicted.npy
    <out_dir>/<case>_<ts>_w_predicted.png
        Predicted w field, with NaN values at building locations.

    <out_dir>/<case>_<ts>_RH_predicted.npy
    <out_dir>/<case>_<ts>_RH_predicted.png
        Relative humidity (RH, %) computed from predicted w and the T raster.

    <out_dir>/<case>_<ts>_w_predicted_meta.json
        Metadata associated with the prediction.

Image colour scale:
    Automatically determined from the minimum and maximum values in the data,
    using the jet colormap.

Humidity conversion:
    e = w * p / (0.62198 + w)
    RH = 100 * e / es(T)

    The saturation vapour pressure es(T) is calculated using the Magnus formula.

    Set --w_units g/kg if w is expressed in grams per kilogram rather than kg/kg.
"""

